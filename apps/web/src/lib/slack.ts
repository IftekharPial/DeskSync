interface SlackNotificationPayload {
  title: string;
  startTime: string;
  endTime: string;
  participants: Array<{
    name: string;
    email: string;
  }>;
  summary: string;
  meetingId: string;
}

interface BookingSlackNotificationPayload {
  booking: {
    id: number;
    hash: string;
    host_user_id: string;
    person_user_id: string;
    first_name: string;
    last_name: string;
    email: string;
    message: string;
    start_time: string;
    end_time: string;
    location_details: {
      online_platform_link?: string;
    };
  };
  calendar_event?: any;
}

interface SlackMessage {
  text: string;
  blocks?: Array<{
    type: string;
    text?: {
      type: string;
      text: string;
    };
    fields?: Array<{
      type: string;
      text: string;
    }>;
    accessory?: any;
  }>;
}

export async function sendSlackNotification(payload: SlackNotificationPayload): Promise<void> {
  const slackWebhookUrl = process.env.SLACK_WEBHOOK_URL;
  
  if (!slackWebhookUrl) {
    throw new Error('SLACK_WEBHOOK_URL environment variable is not configured');
  }

  // Format the start and end times
  const startTime = new Date(payload.startTime).toLocaleString();
  const endTime = new Date(payload.endTime).toLocaleString();
  
  // Create participant list
  const participantList = payload.participants
    .map(p => `• ${p.name} (${p.email})`)
    .join('\n');

  // Create the Slack message with rich formatting
  const slackMessage: SlackMessage = {
    text: `New Meeting Report: ${payload.title}`,
    blocks: [
      {
        type: "header",
        text: {
          type: "plain_text",
          text: `📅 Meeting Report: ${payload.title}`
        }
      },
      {
        type: "section",
        fields: [
          {
            type: "mrkdwn",
            text: `*Meeting ID:*\n${payload.meetingId}`
          },
          {
            type: "mrkdwn",
            text: `*Duration:*\n${startTime} - ${endTime}`
          }
        ]
      },
      {
        type: "section",
        text: {
          type: "mrkdwn",
          text: `*Participants:*\n${participantList}`
        }
      },
      {
        type: "section",
        text: {
          type: "mrkdwn",
          text: `*Summary:*\n${payload.summary}`
        }
      },
      {
        type: "divider"
      },
      {
        type: "context",
        elements: [
          {
            type: "mrkdwn",
            text: `Generated by DailySync Webhook System at ${new Date().toLocaleString()}`
          }
        ]
      }
    ]
  };

  try {
    const response = await fetch(slackWebhookUrl, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(slackMessage),
    });

    if (!response.ok) {
      const errorText = await response.text();
      throw new Error(`Slack API error: ${response.status} ${response.statusText} - ${errorText}`);
    }

    console.log('Slack notification sent successfully');
  } catch (error) {
    console.error('Failed to send Slack notification:', error);
    throw error;
  }
}

