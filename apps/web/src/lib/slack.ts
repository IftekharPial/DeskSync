// Enhanced booking notification function with template support
export async function sendBookingSlackNotification(payload: BookingSlackNotificationPayload, processedTemplate?: string): Promise<void> {
  const slackWebhookUrl = process.env.SLACK_WEBHOOK_URL;

  if (!slackWebhookUrl) {
    throw new Error('SLACK_WEBHOOK_URL environment variable is not configured');
  }

  const { booking } = payload;

  // Use processed template if provided, otherwise create a default message
  let processedMessage: string;

  if (processedTemplate) {
    // Use the template that was already processed by TemplateProcessor
    processedMessage = processedTemplate;
  } else {
    // Fallback to simple default message if no template was processed
    const startTime = new Date(booking.start_time).toLocaleString();
    const endTime = new Date(booking.end_time).toLocaleString();
    const fullName = `${booking.first_name} ${booking.last_name}`.trim();
    const onlinePlatformLink = booking.location_details?.online_platform_link || 'Not provided';

    processedMessage = `📅 *New Booking Received*

👤 *Customer:* ${fullName}
📧 *Email:* ${booking.email}
🕐 *Start Time:* ${startTime}
🕑 *End Time:* ${endTime}
🔗 *Meeting Link:* ${onlinePlatformLink}
👥 *Host ID:* ${booking.host_user_id}
👤 *Person ID:* ${booking.person_user_id}

💬 *Message:*
${booking.message || 'No message provided'}

---
🤖 *Booking Details:*
• ID: ${booking.id}
• Hash: ${booking.hash}`;
  }

  const slackMessage = {
    text: '📅 New Booking Received',
    blocks: [
      {
        type: 'section',
        text: {
          type: 'mrkdwn',
          text: processedMessage
        }
      },
      {
        type: 'divider'
      },
      {
        type: 'context',
        elements: [
          {
            type: 'mrkdwn',
            text: `🤖 Sent via DeskSync Webhook System | Booking ID: ${booking.id}`
          }
        ]
      }
    ]
  };

  try {
    const response = await fetch(slackWebhookUrl, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(slackMessage),
    });

    if (!response.ok) {
      const errorText = await response.text();
      throw new Error(`Slack API error: ${response.status} ${response.statusText} - ${errorText}`);
    }

    console.log('Booking Slack notification sent successfully');
  } catch (error) {
    console.error('Failed to send booking Slack notification:', error);
    throw error;
  }
}

